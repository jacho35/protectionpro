"""Generate backend/analysis/solar_irradiance_data.py (monthly irradiance per South African city).

SCREENING-GRADE data. Each city has a long-term mean daily global horizontal
irradiation (kWh/m2/day) and a climate regime; the twelve monthly values are the
regime's seasonal shape scaled to that annual mean. The annual means are
approximate values typical of published South African solar maps, NOT a
licensed dataset. Replace CITIES' `ghi` (and, if wanted, the shapes) with PVGIS
or SolarGIS monthly values before using results for anything certified.

Run:  python testing/solar/build_irradiance.py
"""
import os

# Seasonal shape per regime: mean daily GHI (kWh/m2/day) by month, Jan..Dec, and
# mean daytime ambient temperature (deg C) by month.
SHAPES = {
    "interior": {
        "ghi": [6.4, 6.0, 5.4, 4.7, 4.0, 3.6, 3.9, 4.6, 5.6, 6.0, 6.3, 6.6],
        "tday": [27, 26, 25, 22, 19, 16, 16, 19, 23, 24, 25, 27],
    },
    "cape": {
        "ghi": [8.0, 7.2, 5.9, 4.2, 3.0, 2.5, 2.8, 3.7, 5.0, 6.5, 7.6, 8.2],
        "tday": [26, 26, 24, 21, 18, 16, 15, 16, 18, 21, 23, 25],
    },
    "east_coast": {
        "ghi": [6.0, 5.7, 5.0, 4.3, 3.7, 3.4, 3.6, 4.2, 4.7, 5.0, 5.5, 6.0],
        "tday": [28, 28, 27, 25, 24, 22, 22, 22, 23, 24, 25, 27],
    },
    "south_coast": {
        "ghi": [7.0, 6.4, 5.3, 4.2, 3.4, 2.9, 3.2, 4.0, 4.9, 5.8, 6.6, 7.1],
        "tday": [25, 25, 24, 22, 20, 19, 18, 18, 19, 21, 23, 24],
    },
}

# name, lat, lon, annual mean daily GHI, regime, design minimum air temperature (deg C)
CITIES = [
    ("Johannesburg", -26.20, 28.04, 5.5, "interior", -4),
    ("Pretoria", -25.75, 28.19, 5.6, "interior", -2),
    ("Cape Town", -33.92, 18.42, 5.0, "cape", 3),
    ("Durban", -29.86, 31.02, 4.9, "east_coast", 7),
    ("Gqeberha (Port Elizabeth)", -33.96, 25.60, 5.0, "south_coast", 4),
    ("Bloemfontein", -29.12, 26.21, 5.9, "interior", -6),
    ("East London", -33.02, 27.91, 4.9, "south_coast", 5),
    ("Polokwane", -23.90, 29.45, 5.7, "interior", -1),
    ("Mbombela (Nelspruit)", -25.47, 30.97, 5.3, "east_coast", 3),
    ("Kimberley", -28.74, 24.77, 6.0, "interior", -4),
    ("Pietermaritzburg", -29.60, 30.38, 5.0, "east_coast", 2),
    ("Rustenburg", -25.67, 27.24, 5.7, "interior", -2),
    ("Upington", -28.45, 21.26, 6.4, "interior", -2),
    ("George", -33.96, 22.46, 4.9, "south_coast", 2),
    ("Mahikeng", -25.86, 25.64, 5.8, "interior", -3),
    ("Richards Bay", -28.78, 32.04, 5.0, "east_coast", 8),
    ("Hermanus", -34.42, 19.24, 4.9, "cape", 3),
]

DAYS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]


def build():
    out = ['"""GENERATED by testing/solar/build_irradiance.py - do not edit by hand.',
           '',
           'Monthly mean daily global horizontal irradiation (kWh/m2/day) and daytime',
           'ambient temperature per South African city. SCREENING GRADE: the annual means',
           'are approximate, not a licensed dataset (see the generator header).',
           '"""',
           '',
           'SOURCE_NOTE = "Screening-grade values; confirm against PVGIS or SolarGIS before certified use."',
           '',
           'CITIES = {']
    for name, lat, lon, ghi, regime, tmin in CITIES:
        shape = SHAPES[regime]
        mean = sum(g * d for g, d in zip(shape["ghi"], DAYS)) / 365.0
        k = ghi / mean
        monthly = [round(g * k, 3) for g in shape["ghi"]]
        out.append(f'    {name!r}: {{"lat": {lat}, "lon": {lon}, "regime": {regime!r}, "tmin_c": {tmin},')
        out.append(f'        "ghi_kwh_m2_day": {monthly},')
        out.append(f'        "tday_c": {shape["tday"]}}},')
    out.append('}')
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    path = os.path.join(os.path.dirname(__file__), "..", "..", "backend", "analysis", "solar_irradiance_data.py")
    with open(path, "w") as f:
        f.write(build())
    print("wrote", os.path.normpath(path))
