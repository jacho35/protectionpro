#!/usr/bin/env python3
"""CBI QF(26)HR hydraulic-magnetic miniature circuit breaker library, 60-125 A, curves 1 and 2.

Writes, from data/cbi_qf26hr_curves.json (never edit the outputs by hand):
  testing/vendor-libraries/cbi_qf26hr_breakers.json   import file — {"entries": [{"kind": "cbs", "data": {...}}]}
  frontend/js/vendor-trip-units-cbi-qf26hr.js         the trip-unit profiles the entries point at (TRIP_UNITS)

Source: CBI data sheet QF26HR-SERIES-DAT REV. C (April 2022) — Technical Data (Icu), Long Code /
Ordering Information (ratings 60, 70, 80, 90, 100, 125 A; time delays 1 and 2 and their instantaneous
trip points), Time Delay Curve pages (curves 1 and 2, minimum + maximum at 30 C, digitised from the
PDF's vector charts by digitize_cbi_qf.py and checked against the table printed with curve 1:
within 3 % at every column from 130 % to 2000 %). The "HR" is the high-rating mechanism: the charts
are the same as the QF(26)LR's (identical to 0.01 %), as is the 100 % rating independent of ambient.

What the numbers mean
---------------------
The maximum curve is the long-time curve the engines clear on (`thermal_curve`), the minimum is the
fastest the breaker may trip (`long_time.min_points`), so the TCC draws the band. No trip below
1.05 x In, trips above 1.30 x In. The sheet's instantaneous trip point is 10-20 x In (curve 1, orange
handle) and 5-10 x In (curve 2): the point where the times start to collapse. The modelled pickup band
is where the charts reach their flat times (curve 1: 17.6-29.9 x In, curve 2: 9.9-17.4 x In; 5 ms /
20 ms), so the clearing time is the published curve at every current. The curve letter is the IEC
60898-1 band the sheet's trip point matches: 1 = D (10-20), 2 = C (5-10).

Known simplifications (recorded, not hidden)
--------------------------------------------
* Icu is the VC 8036 (SANS 556-1) figure, 5 kA at 240 / 415 V; the sheet gives 6 kA for the IEC /
  DIN version. The sheet publishes no Ics for the circuit breaker, so none is carried.
* The 60 A rating is listed in the ordering table and for GB/T 14048.2 and UL 489 (60-100 A, 10 kA AIC,
  120 / 240 V), while the DIN / EN 60947-2 technical data starts at 70 A: it is included as ordered.
* The UL 489 version, the 125 A switch disconnector and the pole count (1, 1+N, 2, 3, 3+N) are not modelled.
* The curves are the 30 C curves; the temperature-compensation curve is "available on request".

Run:  python testing/vendor-libraries/build_cbi_qf26hr.py
"""
import json
import os

import cbi_curves as C

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MAKER = "CBI"
CAT = "QF26HR-SERIES-DAT REV. C"
SOURCE = "CBI data sheet QF26HR-SERIES-DAT REV. C (April 2022)"
RATINGS = [60, 70, 80, 90, 100, 125]
CURVES = {"1": ("D", "10-20"), "2": ("C", "5-10")}       # IEC curve letter, the sheet's instantaneous trip point (x In)


def _pid(c):
    return f"cbi_qf26hr_c{c}"


def profiles():
    data = json.load(open(os.path.join(HERE, "data", "cbi_qf26hr_curves.json")))["curves"]
    return {_pid(c): C.tm_profile(MAKER, f"CBI QF(26)HR thermal-magnetic, curve {c}", CAT, d["max"], d["min"])
            for c, d in data.items()}


def entries(prof):
    out = []
    for c, (letter, band) in CURVES.items():
        mid = prof[_pid(c)]["dials"]["magnetic_pickup"]["def"]
        for inn in RATINGS:
            out.append({"kind": "cbs", "data": {
                "id": f"cbi_qf26hr_c{c}_{inn}", "name": f"CBI QF26HR {inn} A curve {c}", "cb_type": "mcb",
                "mcb_curve": letter, "manufacturer": MAKER, "series": "QF(26)HR", "model": f"QF26HR curve {c}",
                "trip_rating_a": inn, "frame_a": 125, "rated_voltage_kv": 0.4, "breaking_ka": 5,
                "thermal_pickup": 1.0, "magnetic_pickup": mid, "long_time_delay": 10,
                "trip_units": [_pid(c)], "default_trip_unit": _pid(c), "source": SOURCE,
                "check": f"sheet instantaneous trip point {band} x In; modelled pickup band = where the curves reach their flat times",
            }})
    return out


def js_profiles(p):
    return (
        "// GENERATED by testing/vendor-libraries/build_cbi_qf26hr.py — do not edit by hand.\n"
        "// CBI QF(26)HR hydraulic-magnetic MCB, time-delay curves 1 and 2: `curve.thermal` is the published maximum\n"
        "// curve (x In, s), `curve.tol.long_time.min_points` the minimum curve (copied onto the breaker as\n"
        "// `thermal_curve` / `trip_tol`, see cbTripBand); the magnetic pickup is a multiple of In.\n"
        f"Object.assign(TRIP_UNITS, {json.dumps(p, indent=1)});\n"
    )


if __name__ == "__main__":
    prof = profiles()
    ents = entries(prof)
    ids = [e["data"]["id"] for e in ents]
    assert len(ids) == len(set(ids))
    with open(os.path.join(HERE, "cbi_qf26hr_breakers.json"), "w") as f:
        json.dump({"entries": ents}, f, indent=1)
        f.write("\n")
    with open(os.path.join(ROOT, "frontend", "js", "vendor-trip-units-cbi-qf26hr.js"), "w") as f:
        f.write(js_profiles(prof))
    for k, v in prof.items():
        t = v["curve"]["tol"]
        print(k, "Im", v["dials"]["magnetic_pickup"]["def"], "+/-", t["instantaneous"]["pickup_tol"], "pickup", t["pickup"])
    print(f"{len(ents)} entries, {len(prof)} trip-unit profiles")
