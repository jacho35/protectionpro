#!/usr/bin/env python3
"""CBI QF(26)LR hydraulic-magnetic miniature circuit breaker library, 5-63 A, curves 1 and 2.

Writes, from data/cbi_qf26lr_curves.json (never edit the outputs by hand):
  testing/vendor-libraries/cbi_qf26lr_breakers.json   import file — {"entries": [{"kind": "cbs", "data": {...}}]}
  frontend/js/vendor-trip-units-cbi-qf26lr.js         the trip-unit profiles the entries point at (TRIP_UNITS)

Source: CBI data sheet QF26LR-SERIES-DAT REV. B (April 2022) — Technical Data (Icu / Ics), Long Code /
Ordering Information (time delays 1, 2, 3, 9 and their instantaneous trip points), Time Delay Curve pages
(curves 1 and 2, minimum + maximum at 30 C, digitised from the PDF's vector charts by
digitize_cbi_qf.py and checked against the table printed with curve 1: within 3 % at every
column from 130 % to 2000 %).

What the numbers mean
---------------------
Hydraulic-magnetic, 100 % rated: the trip points are not affected by ambient temperature. The
maximum curve is the long-time curve the engines clear on (`thermal_curve`), the minimum is the
fastest the breaker may trip (`long_time.min_points`), so the TCC draws the band. No trip below
1.05 x In, trips above 1.30 x In. The sheet's instantaneous trip point is 10-20 x In (curve 1,
orange handle) and 5-10 x In (curve 2): the point where the times start to collapse. The modelled
pickup band is where the charts reach their flat times (curve 1: 17.6-29.9 x In, curve 2: 9.9-17.5
x In; 5 ms / 20 ms), so the clearing time is the published curve at every current. The curve
letter is the IEC 60898-1 band the sheet's trip point matches: 1 = D (10-20), 2 = C (5-10).

Known simplifications (recorded, not hidden)
--------------------------------------------
* Curves 3 (short delay, 3-5 x In) and 9 (long delay, 7-12 x In) are orderable but their
  charts are not in the data sheet: not modelled.
* The Icu / Ics are the SANS IEC 60947-2 (VC 8036) version's: 5 kA / 2.5 kA at 240 / 415 V. The
  GB 14048.2 version (Icu 6 kA, Ics 3 kA, Icw 6 kA) is not offered.
* Ratings are those of the sheet's internal-impedance table from the 5 A minimum (5, 6, 10, 15,
  20, 25, 30, 32, 40, 50, 60, 63 A); "subject to certification" per rating. The internal
  impedance table and the pole count (1, 2, 1+N, 3, 3+N) are not carried.
* The curves are the 30 C curves; the temperature-compensation curve is "available on request".

Run:  python testing/vendor-libraries/build_cbi_qf26lr.py
"""
import json
import os

import cbi_curves as C

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MAKER = "CBI"
CAT = "QF26LR-SERIES-DAT REV. B"
SOURCE = "CBI data sheet QF26LR-SERIES-DAT REV. B (April 2022)"
RATINGS = [5, 6, 10, 15, 20, 25, 30, 32, 40, 50, 60, 63]
CURVES = {"1": ("D", "10-20"), "2": ("C", "5-10")}       # IEC curve letter, the sheet's instantaneous trip point (x In)


def _pid(c):
    return f"cbi_qf26lr_c{c}"


def profiles():
    data = json.load(open(os.path.join(HERE, "data", "cbi_qf26lr_curves.json")))["curves"]
    return {_pid(c): C.tm_profile(MAKER, f"CBI QF(26)LR thermal-magnetic, curve {c}", CAT, d["max"], d["min"])
            for c, d in data.items()}


def entries(prof):
    out = []
    for c, (letter, band) in CURVES.items():
        mid = prof[_pid(c)]["dials"]["magnetic_pickup"]["def"]
        for inn in RATINGS:
            out.append({"kind": "cbs", "data": {
                "id": f"cbi_qf26lr_c{c}_{inn}", "name": f"CBI QF26LR {inn} A curve {c}", "cb_type": "mcb",
                "mcb_curve": letter, "manufacturer": MAKER, "series": "QF(26)LR", "model": f"QF26LR curve {c}",
                "trip_rating_a": inn, "frame_a": 63, "rated_voltage_kv": 0.4, "breaking_ka": 5, "ics_pct": 50,
                "thermal_pickup": 1.0, "magnetic_pickup": mid, "long_time_delay": 10,
                "trip_units": [_pid(c)], "default_trip_unit": _pid(c), "source": SOURCE,
                "check": f"sheet instantaneous trip point {band} x In; modelled pickup band = where the curves reach their flat times",
            }})
    return out


def js_profiles(p):
    return (
        "// GENERATED by testing/vendor-libraries/build_cbi_qf26lr.py — do not edit by hand.\n"
        "// CBI QF(26)LR hydraulic-magnetic MCB, time-delay curves 1 and 2: `curve.thermal` is the published maximum\n"
        "// curve (x In, s), `curve.tol.long_time.min_points` the minimum curve (copied onto the breaker as\n"
        "// `thermal_curve` / `trip_tol`, see cbTripBand); the magnetic pickup is a multiple of In.\n"
        f"Object.assign(TRIP_UNITS, {json.dumps(p, indent=1)});\n"
    )


if __name__ == "__main__":
    prof = profiles()
    ents = entries(prof)
    ids = [e["data"]["id"] for e in ents]
    assert len(ids) == len(set(ids))
    with open(os.path.join(HERE, "cbi_qf26lr_breakers.json"), "w") as f:
        json.dump({"entries": ents}, f, indent=1)
        f.write("\n")
    with open(os.path.join(ROOT, "frontend", "js", "vendor-trip-units-cbi-qf26lr.js"), "w") as f:
        f.write(js_profiles(prof))
    for k, v in prof.items():
        t = v["curve"]["tol"]
        print(k, "Im", v["dials"]["magnetic_pickup"]["def"], "+/-", t["instantaneous"]["pickup_tol"], "pickup", t["pickup"])
    print(f"{len(ents)} entries, {len(prof)} trip-unit profiles")
