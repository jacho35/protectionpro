#!/usr/bin/env python3
"""CBI J-Series (J-Frame) hydraulic-magnetic moulded-case circuit breakers: JS25 (1 pole) and J25S (3 pole), 50-250 A.

Writes, from data/cbi_jframe_curves.json (never edit the outputs by hand):
  testing/vendor-libraries/cbi_jframe_breakers.json   import file — {"entries": [{"kind": "cbs", "data": {...}}]}
  frontend/js/vendor-trip-units-cbi-jframe.js         the trip-unit profiles the entries point at (TRIP_UNITS)

Source: CBI data sheet J-SERIES-DAT REV.A (April 2026, DCN 2605001): Technical Data (ratings, interrupting capacity),
Ordering Information (ratings per type) and the two Time Delay Curves pages (page 4: 225-250 A; page 5: 12-200 A AC),
minimum + maximum at 30 C, digitised from the PDF's vector charts by digitize_cbi_qf.py and checked against the trip-time
table printed under each (within ~14 % in time, which on the steep parts is a few percent in current).

What the numbers mean
---------------------
Hydraulic-magnetic, 100 % rated: the trip points are not affected by ambient temperature. The maximum curve is the
long-time curve the engines clear on (`thermal_curve`), the minimum is the fastest the breaker may trip
(`long_time.min_points`), so the TCC draws the band. No trip below 1.05 x In, trips above 1.30 x In. The instantaneous
band is where the two curves reach their flat times: minimum 4 ms from ~13 x In; maximum 0.02 s from ~14.5 x In for the
50-200 A ratings, but 1 s from ~9.8 x In for the 225 and 250 A ratings (that curve never clears faster than 1 s).

Known simplifications (recorded, not hidden)
--------------------------------------------
* The sheet gives no Ics, so none is carried. Icu: JS25 (1 pole) 25 kA at 240 V; J25S (3 pole) 25 kA at 415 V (15 kA at 525 V).
* The two curves are the sheet's "225-250 A" and "12-200 A AC" charts; the 12-200 A chart is also headed "12-250 A DC", which
  is not modelled.
* The J25SN switch disconnector is not a breaker and is not included. Accessories (shunt trips, auxiliaries, UVR) and terminals
  are not modelled. The temperature-compensation curve is "available on request".
* Ratings are the ordering table's: JS25 80, 100, 125, 150, 200, 250 A; J25S 50, 60, 80, 100, 125, 150, 160, 175, 200, 225, 250 A.

Run:  python testing/vendor-libraries/build_cbi_jframe.py
"""
import json
import os

import cbi_curves as C

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MAKER = "CBI"
CAT = "J-SERIES-DAT REV.A"
SOURCE = "CBI data sheet J-SERIES-DAT REV.A (April 2026)"
TYPES = {   # model -> (poles, rated voltage kV, Icu kA, ratings)
    "JS25": ("1 pole", 0.24, 25, [80, 100, 125, 150, 200, 250]),
    "J25S": ("3 pole", 0.4, 25, [50, 60, 80, 100, 125, 150, 160, 175, 200, 225, 250]),
}


def _curve(inn):
    """The sheet's chart for a rating: 225-250 A has its own, 12-200 A the other."""
    return "a" if inn >= 225 else "b"


def profiles():
    data = json.load(open(os.path.join(HERE, "data", "cbi_jframe_curves.json")))["curves"]
    label = {"a": "225-250 A", "b": "up to 200 A"}
    return {f"cbi_jframe_{c}": C.tm_profile(MAKER, f"CBI J-Series thermal-magnetic, {label[c]}", CAT, d["max"], d["min"])
            for c, d in data.items()}


def entries(prof):
    out = []
    for model, (poles, kv, icu, ratings) in TYPES.items():
        for inn in ratings:
            pid = f"cbi_jframe_{_curve(inn)}"
            out.append({"kind": "cbs", "data": {
                "id": f"cbi_{model.lower()}_{inn}", "name": f"CBI {model} {inn} A", "cb_type": "mccb",
                "manufacturer": MAKER, "series": "J-Series", "model": model,
                "trip_rating_a": inn, "frame_a": 250, "rated_voltage_kv": kv, "breaking_ka": icu,
                "thermal_pickup": 1.0, "magnetic_pickup": prof[pid]["dials"]["magnetic_pickup"]["def"], "long_time_delay": 10,
                "trip_units": [pid], "default_trip_unit": pid, "source": SOURCE,
                "check": f"{poles}; Icu {icu} kA at {int(kv * 1000)} V" + ("; the 225-250 A curve never clears faster than 1 s" if inn >= 225 else "")
                         + "; instantaneous band = where the sheet's curves reach their flat times",
            }})
    return out


def js_profiles(p):
    return (
        "// GENERATED by testing/vendor-libraries/build_cbi_jframe.py — do not edit by hand.\n"
        "// CBI J-Series (JS25 / J25S) hydraulic-magnetic MCCB trip-unit profiles: `curve.thermal` is the published maximum\n"
        "// curve (x In, s), `curve.tol.long_time.min_points` the minimum curve (copied onto the breaker as\n"
        "// `thermal_curve` / `trip_tol`, see cbTripBand); the magnetic pickup is a multiple of In.\n"
        f"Object.assign(TRIP_UNITS, {json.dumps(p, indent=1)});\n"
    )


if __name__ == "__main__":
    prof = profiles()
    ents = entries(prof)
    ids = [e["data"]["id"] for e in ents]
    assert len(ids) == len(set(ids))
    with open(os.path.join(HERE, "cbi_jframe_breakers.json"), "w") as f:
        json.dump({"entries": ents}, f, indent=1)
        f.write("\n")
    with open(os.path.join(ROOT, "frontend", "js", "vendor-trip-units-cbi-jframe.js"), "w") as f:
        f.write(js_profiles(prof))
    for k, v in prof.items():
        t = v["curve"]["tol"]
        print(f"  {k}: Im {v['dials']['magnetic_pickup']['def']} +/-{t['instantaneous']['pickup_tol']}, pickup {t['pickup']}, hold {t['instantaneous']['hold_s']} break {t['instantaneous']['break_s']}")
    print(f"{len(ents)} entries, {len(prof)} trip-unit profiles")
