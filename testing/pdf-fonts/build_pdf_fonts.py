"""Build frontend/js/lib/pdf-fonts.js — the fonts the vector drawing PDFs embed.

jsPDF's built-in Helvetica / Courier only cover WinAnsi, so Ω, Δ, φ, √, ≤ …
in a diagram's data labels would print as garbage. This subsets Liberation Sans
and Liberation Mono (SIL OFL 1.1; metric-compatible with Arial / Courier New, the
fonts the diagram uses) to the characters a drawing needs and writes them as
base64 into one script that VectorPDF loads on demand.

    python testing/pdf-fonts/build_pdf_fonts.py [font dir]

Default font dir: /usr/share/fonts/truetype/liberation2 (Debian fonts-liberation2).
"""
import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'frontend/js/lib/pdf-fonts.js'
SRC = Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation2')

# Basic Latin, Latin-1, Latin Extended-A, Greek, punctuation, super/subscripts,
# letterlike (℃ №), arrows, math operators, box drawing bits, geometric shapes.
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x370, 0x3FF), (0x2010, 0x2044), (0x2070, 0x209F),
          (0x20AC, 0x20AC), (0x2100, 0x2135), (0x2190, 0x21FF), (0x2200, 0x22FF),
          (0x2300, 0x23FF), (0x25A0, 0x25FF)]
FONTS = {
    'PPSans-normal': 'LiberationSans-Regular.ttf',
    'PPSans-bold': 'LiberationSans-Bold.ttf',
    'PPMono-normal': 'LiberationMono-Regular.ttf',
    'PPMono-bold': 'LiberationMono-Bold.ttf',
}


def build(path):
    font = TTFont(path)
    opts = subset.Options()
    opts.layout_features = []
    opts.hinting = False
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[u for a, b in RANGES for u in range(a, b + 1)])
    sub.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode('ascii')


def main():
    lines = [
        '/* GENERATED by testing/pdf-fonts/build_pdf_fonts.py — never hand-edit.',
        ' * Liberation Sans / Liberation Mono, subset. Copyright (c) 2012 Red Hat, Inc.,',
        ' * licensed under the SIL Open Font License 1.1 (https://openfontlicense.org). */',
        'window.PDF_FONTS = {',
    ]
    for key, name in FONTS.items():
        b64 = build(SRC / name)
        lines.append(f"  '{key}': '{b64}',")
        print(key, len(b64) // 1024, 'KiB')
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n')
    print('wrote', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
