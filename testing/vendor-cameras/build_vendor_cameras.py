"""Builds frontend/js/vendor-cameras.js (VENDOR_CAMERAS) from testing/vendor-cameras/cameras.json. Run: python testing/vendor-cameras/build_vendor_cameras.py
Fails on a missing field so a half-entered model never reaches the app."""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent.parent / "frontend" / "js" / "vendor-cameras.js"
REQ = ("id", "vendor", "model", "kind", "resW", "resH", "mp", "hfov", "source")


def main():
    data = json.loads((HERE / "cameras.json").read_text(encoding="utf-8"))
    ids = set()
    for c in data["cameras"]:
        miss = [k for k in REQ if c.get(k) is None]
        assert not miss, f"{c.get('id')}: missing {miss}"
        assert c["id"] not in ids, f"duplicate {c['id']}"
        ids.add(c["id"])
        assert c["kind"] in ("dome", "bullet", "ptz"), c["id"]
        assert 0 < c["hfov"] < 180, c["id"]
        if c.get("hfovTele") is not None:
            assert c["hfovTele"] < c["hfov"], c["id"]
        assert c["source"].startswith("https://"), c["id"]
    # null fields are left out of the row (a field the maker does not publish is absent)
    rows = [{k: v for k, v in c.items() if v is not None} for c in data["cameras"]]
    body = json.dumps(rows, indent=1, ensure_ascii=False)
    OUT.write_text("// GENERATED by testing/vendor-cameras/build_vendor_cameras.py from testing/vendor-cameras/cameras.json: do not edit by hand.\n"
                   "// Manufacturer CCTV camera data (their published figures; each row names its source page).\n"
                   f"const VENDOR_CAMERAS = {body};\n", encoding="utf-8")
    print(f"{len(rows)} cameras -> {OUT}")


if __name__ == "__main__":
    main()
