"""Builds frontend/js/vendor-aps.js (VENDOR_APS) from testing/vendor-aps/aps.json. Run: python testing/vendor-aps/build_vendor_aps.py
Fails on a missing field so a half-entered model never reaches the app."""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent.parent / "frontend" / "js" / "vendor-aps.js"
REQ = ("id", "vendor", "model", "standard", "watts", "bands", "source")


def main():
    data = json.loads((HERE / "aps.json").read_text(encoding="utf-8"))
    ids = set()
    for a in data["aps"]:
        miss = [k for k in REQ if k not in a]
        assert not miss, f"{a.get('id')}: missing {miss}"
        assert a["id"] not in ids, f"duplicate {a['id']}"
        ids.add(a["id"])
        assert a["bands"] and set(a["bands"]) <= {"2.4", "5", "6"}, a["id"]
        for b, v in a["bands"].items():
            assert all(k in v for k in ("tx", "gain", "streams")), (a["id"], b)
    body = json.dumps(data["aps"], indent=1, ensure_ascii=False)
    OUT.write_text("// GENERATED by testing/vendor-aps/build_vendor_aps.py from testing/vendor-aps/aps.json: do not edit by hand.\n"
                   "// Manufacturer access-point data (their published figures; each row names its source page).\n"
                   f"const VENDOR_APS = {body};\n", encoding="utf-8")
    print(f"{len(data['aps'])} access points -> {OUT}")


if __name__ == "__main__":
    main()
